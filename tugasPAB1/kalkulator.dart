class Kalkulator {
  double tambah(double angka1, double angka2) {
    return angka1 + angka2;
  }

  double kurang(double angka1, double angka2) {
    return angka1 - angka2;
  }

  double kali(double angka1, double angka2) {
    return angka1 * angka2;
  }

  double bagi(double angka1, double angka2) {
    return angka1 / angka2;
  }
}